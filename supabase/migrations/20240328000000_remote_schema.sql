CREATE OR REPLACE FUNCTION "private"."get_family_id"() RETURNS integer
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
DECLARE
    family_id integer;
begin
  SELECT p.family_id INTO family_id
    FROM public.parents p
    WHERE p.user_id = (SELECT auth.uid() as uid);

    -- If not found in parents, try to find it in the children table
    IF family_id IS NULL THEN
        SELECT c.family_id INTO family_id
        FROM public.children c
        WHERE c.user_id = (SELECT auth.uid() as uid);
    END IF;

    RETURN family_id;
end;
$$;


ALTER FUNCTION "private"."get_family_id"() OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."handle_new_user"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$
begin
  insert into public.profiles (id, full_name, avatar_url)
  values (new.id, new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'avatar_url');
  return new;
end;
$$;


